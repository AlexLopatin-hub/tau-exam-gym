package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"html"
	"log"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/FurqanSoftware/goldmark-katex"
	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/ast"
	"github.com/yuin/goldmark/extension"
	"github.com/yuin/goldmark/parser"
	"github.com/yuin/goldmark/renderer"
	"github.com/yuin/goldmark/util"
)

const output = "data/lecture_pages.json"

var tableScroll = strings.NewReplacer(
	"<table>\n", "<div class=\"lecture-table\" role=\"region\" aria-label=\"Таблица лекции\" tabindex=\"0\"><table>\n",
	"</table>\n", "</table></div>\n",
)

func main() {
	log.SetFlags(0)
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

func generate() error {
	files, err := filepath.Glob("lectures/*.md")
	if err != nil {
		return err
	}

	// Parse math before Markdown can interpret its punctuation.
	markdown := goldmark.New(
		goldmark.WithExtensions(extension.GFM),
		goldmark.WithParserOptions(
			parser.WithBlockParsers(util.Prioritized(&katex.BlockParser{}, 50)),
			parser.WithInlineParsers(util.Prioritized(&katex.Parser{}, 0)),
		),
		goldmark.WithRendererOptions(renderer.WithNodeRenderers(util.Prioritized(latexRenderer{}, 0))),
	)
	pages := make(map[string]string, len(files))
	for _, filename := range files {
		name := strings.TrimSuffix(filepath.Base(filename), ".md")
		if _, err := time.Parse("01.02", name); err != nil {
			return fmt.Errorf("lecture %s: %w", filename, err)
		}
		source, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		var body bytes.Buffer
		source = bytes.ReplaceAll(source, []byte("\r\n"), []byte("\n"))
		if err := markdown.Convert(source, &body); err != nil {
			return fmt.Errorf("lecture %s: %w", filename, err)
		}
		pages[name] = tableScroll.Replace(body.String())
	}

	var generated bytes.Buffer
	encoder := json.NewEncoder(&generated)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(pages); err != nil {
		return err
	}
	if current, err := os.ReadFile(output); err == nil && bytes.Equal(current, generated.Bytes()) {
		return nil
	}

	tmp, err := os.CreateTemp(filepath.Dir(output), "lecture_pages-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	_, writeErr := tmp.Write(generated.Bytes())
	closeErr := tmp.Close()
	if writeErr != nil {
		return writeErr
	}
	if closeErr != nil {
		return closeErr
	}
	return os.Rename(tmp.Name(), output)
}

type latexRenderer struct{}

func (latexRenderer) RegisterFuncs(reg renderer.NodeRendererFuncRegisterer) {
	reg.Register(katex.KindInline, renderLatex)
	reg.Register(katex.KindBlock, renderLatex)
}

func renderLatex(w util.BufWriter, source []byte, n ast.Node, entering bool) (ast.WalkStatus, error) {
	if !entering {
		return ast.WalkContinue, nil
	}
	var equation []byte
	tag, delimiter := "span", "$"
	switch node := n.(type) {
	case *katex.Inline:
		equation = node.Equation
		if node.Display {
			delimiter = "$$"
		}
	case *katex.Block:
		equation = node.Equation(source)
		tag, delimiter = "div", "$$"
	}
	_, err := fmt.Fprintf(w, "<%s class=\"latex-source\">%s%s%s</%s>", tag, delimiter, html.EscapeString(string(equation)), delimiter, tag)
	return ast.WalkContinue, err
}
