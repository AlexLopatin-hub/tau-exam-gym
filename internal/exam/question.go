func loadQuestions() ([]Question, error) {
	path := os.Getenv("QUESTION_BANK")
	questions := demoQuestions
	if path != "" {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read question bank: %w", err)
		}
		questions = nil
		if err := json.Unmarshal(data, &questions); err != nil {
			return nil, fmt.Errorf("parse question bank: %w", err)
		}
	}
	if len(questions) == 0 {
		return nil, fmt.Errorf("question bank is empty")
	}
	seen := map[string]bool{}
	difficulties := map[string]bool{"лёгкий": true, "средний": true, "сложный": true}
	for _, q := range questions {
		if q.ID == "" || q.Text == "" || q.Answer == "" || q.Topic == "" || q.Difficulty == "" {
			return nil, fmt.Errorf("question has an empty required field")
		}
		if seen[q.ID] {
			return nil, fmt.Errorf("duplicate question id %q", q.ID)
		}
		if !difficulties[q.Difficulty] {
			return nil, fmt.Errorf("question %q has invalid difficulty %q", q.ID, q.Difficulty)
		}
		seen[q.ID] = true
	}
	return questions, nil
}
